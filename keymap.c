bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    mod_state = get_mods();

    switch (keycode) {
        case SYMB:
            if (record->event.pressed) {
                layer_on(_SYMB);
                update_tri_layer(_SYMB, _NUMP, _TUNE);
            } else {
                layer_off(_SYMB);
                update_tri_layer(_SYMB, _NUMP, _TUNE);
            }
            return false;

        case MT(SYMB,KC_ENT):
            if (record->tap.count && record->event.pressed) {
                tap_code16(KC_ENT);
            } else if (record->event.pressed) {
                layer_on(_SYMB);
                update_tri_layer(_SYMB, _NUMP, _TUNE);
            } else {
                layer_off(_SYMB);
                update_tri_layer(_SYMB, _NUMP, _TUNE);
            }
            return false;
            
        case MT(NUMP,KC_ENT):
            if (record->tap.count && record->event.pressed) {
                tap_code16(KC_ENT);
            } else if (record->event.pressed) {
                layer_on(_NUMP);
                update_tri_layer(_SYMB, _NUMP, _TUNE);
            } else {
                layer_off(_NUMP);
                update_tri_layer(_SYMB, _NUMP, _TUNE);
            }
            return false;

        case MT(KC_LGUI,KC_TAB):
            if (record->tap.count && record->event.pressed) {
                tap_code16(KC_TAB);
            } else if (record->event.pressed) { 
                register_code16(KC_LCMD);
            } else {
                unregister_code16(KC_LCMD);
            }
            return false;

        case RALT_T(KC_CAPS):
            if (record->tap.count && record->event.pressed) {
                tap_code16(KC_CAPS);
                return false;
            }
            break;   

        case LCTL_T(KC_LABK):
            if (record->tap.count && record->event.pressed) {
                if (mod_state & MOD_MASK_SHIFT) {
                    tap_code16(KC_RABK); // >
                } else {
                    tap_code16(KC_LABK); // <
                }
            } else if (record->event.pressed) {
                register_code16(KC_LCTL);
            } else {
                unregister_code16(KC_LCTL);
            }
            return false; 

        case LSFT_T(KC_LPRN):
            if (record->tap.count && record->event.pressed) {
                if (mod_state & MOD_MASK_SHIFT) {
                    tap_code16(KC_RPRN); // )
                } else {
                    tap_code16(KC_LPRN); // (
                }
            } else if (record->event.pressed) {
                register_code16(KC_LSFT);
            } else {
                unregister_code16(KC_LSFT);
            }
            return false; 

        case OS: 
            if (record->event.pressed) {
                if (IS_LAYER_OFF(_MACOS)) {
                    layer_on(_MACOS);
                } else {
                    layer_off(_MACOS);
                }
            }
            return false;     
    }
    return true;
}
